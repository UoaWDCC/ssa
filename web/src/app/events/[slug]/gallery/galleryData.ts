export interface GalleryImage {
  id: number
  url: string
  alt: string
}

function createGalleryImages(
  folder: string,
  eventName: string,
  filenames: string[],
): GalleryImage[] {
  return filenames.map((filename, index) => ({
    id: index + 1,
    url: `/event-gallery/${folder}/${filename}`,
    alt: `${eventName} event photo ${index + 1}`,
  }))
}

